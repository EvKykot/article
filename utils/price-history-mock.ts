// Types for price history data
export type RawPriceHistory = {
  time: number
  value: number
}

function normalizeRawPriceHistory(history: RawPriceHistory[]): RawPriceHistory[] {
  const seen = new Set<number>()
  return history
    .sort((a, b) => a.time - b.time)
    .filter((item) => {
      if (seen.has(item.time)) return false
      seen.add(item.time)
      return true
    })
}

