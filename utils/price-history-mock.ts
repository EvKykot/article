export const rawPriceHistory = normalizeRawPriceHistory(initialPriceHistory)

export const generateNextDataPoint = (lastPoint: RawPriceHistory): RawPriceHistory => {
  let change = 0

  const eventProb = Math.random()
  if (eventProb > 0.95) {
    change = (Math.random() * 2 - 1) * 1.5
  } else if (eventProb > 0.7) {
    change = (Math.random() * 1 - 0.5) * 0.5
  } else {
    change = (Math.random() * 0.4 - 0.2) * 0.3
  }

  // Ensure price stays in reasonable range
  const newValue = Math.max(50, Math.min(1500, lastPoint.value + change))

  return {
    time: Date.now() / 1000,
    value: Number(newValue.toFixed(2)),
  }
}

export const usePriceHistory = () => {
  // Always return the normalized data on server side
  if (typeof window === 'undefined') {
    return rawPriceHistory
  }

  // On client side, use state to track price history
  const [priceHistory, setPriceHistory] = React.useState<RawPriceHistory[]>([])

  // Initialize state with normalized data on first render
  React.useEffect(() => {
    setPriceHistory(rawPriceHistory)
  }, [])

  // Set up interval to update price data
  React.useEffect(() => {
    if (priceHistory.length === 0) return

    const interval = setInterval(() => {
      setPriceHistory((currentHistory) => {
        if (currentHistory.length === 0) return rawPriceHistory

        const lastPoint = currentHistory[currentHistory.length - 1]
        const newPoint = generateNextDataPoint(lastPoint)

        // Add new point to history
        return [...currentHistory, newPoint].slice(-500) // Keep last 500 points for performance
      })
    }, 1000)

    return () => clearInterval(interval)
  }, [priceHistory.length]) // Fixed dependency array - using priceHistory.length directly

  return priceHistory
}
